CREATE TABLE public.realtime_outbox (
    id              bigint       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_type      varchar(100) NOT NULL,
    entity_type     varchar(80)  NOT NULL,
    entity_id       varchar(120),
    audience        varchar(20)  NOT NULL DEFAULT 'AUTHENTICATED',
    target_user_id  uuid,
    payload         jsonb        NOT NULL DEFAULT '{}'::jsonb,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    claimed_at      timestamptz,
    published_at    timestamptz,
    attempts        integer      NOT NULL DEFAULT 0,
    last_error      text,
    CONSTRAINT chk_realtime_outbox_audience
        CHECK (audience IN ('AUTHENTICATED', 'ADMIN', 'USER')),
    CONSTRAINT fk_realtime_outbox_target_user
        FOREIGN KEY (target_user_id) REFERENCES public.app_users(id) ON DELETE CASCADE,
    CONSTRAINT chk_realtime_outbox_target
        CHECK ((audience = 'USER') = (target_user_id IS NOT NULL))
);

CREATE INDEX idx_realtime_outbox_pending
    ON public.realtime_outbox (id)
    WHERE published_at IS NULL;

CREATE INDEX idx_realtime_outbox_published
    ON public.realtime_outbox (published_at)
    WHERE published_at IS NOT NULL;

CREATE OR REPLACE FUNCTION public.enqueue_realtime_change()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    change_operation text := CASE TG_OP
        WHEN 'INSERT' THEN 'created'
        WHEN 'UPDATE' THEN 'updated'
        WHEN 'DELETE' THEN 'deleted'
    END;
BEGIN
    IF TG_TABLE_NAME = 'events' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, payload
        ) VALUES (
            'event.created', 'event', NEW.id::text,
            jsonb_build_object(
                'deviceId', NEW.device_id::text,
                'eventType', NEW.event_type
            )
        );
        RETURN NEW;
    ELSIF TG_TABLE_NAME = 'devices' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, payload
        ) VALUES (
            'device.' || change_operation, 'device', COALESCE(NEW.id, OLD.id)::text,
            CASE WHEN TG_OP = 'DELETE' THEN '{}'::jsonb ELSE
                jsonb_build_object('status', NEW.status, 'siteId', NEW.site_id::text)
            END
        );
    ELSIF TG_TABLE_NAME = 'incidents' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, payload
        ) VALUES (
            'incident.' || change_operation, 'incident', COALESCE(NEW.id, OLD.id)::text,
            CASE WHEN TG_OP = 'DELETE' THEN '{}'::jsonb ELSE
                jsonb_build_object('deviceId', NEW.device_id::text, 'status', NEW.status)
            END
        );
    ELSIF TG_TABLE_NAME = 'sites' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, payload
        ) VALUES (
            'site.' || change_operation, 'site', COALESCE(NEW.id, OLD.id)::text, '{}'::jsonb
        );
    ELSIF TG_TABLE_NAME = 'app_users' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'user.' || change_operation, 'user', COALESCE(NEW.id, OLD.id)::text,
            'ADMIN', '{}'::jsonb
        );
    ELSIF TG_TABLE_NAME = 'whatsapp_recipients' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'whatsapp_recipient.' || change_operation, 'whatsapp_recipient',
            COALESCE(NEW.id, OLD.id)::text, 'ADMIN', '{}'::jsonb
        );
    ELSIF TG_TABLE_NAME = 'notification_templates' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'notification_template.' || change_operation, 'notification_template',
            COALESCE(NEW.event_type, OLD.event_type), 'ADMIN', '{}'::jsonb
        );
    ELSIF TG_TABLE_NAME = 'audit_logs' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'audit_log.created', 'audit_log', NEW.id::text, 'ADMIN', '{}'::jsonb
        );
        RETURN NEW;
    ELSIF TG_TABLE_NAME = 'login_attempts' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'login_attempt.created', 'login_attempt', NEW.id::text, 'ADMIN', '{}'::jsonb
        );
        RETURN NEW;
    ELSIF TG_TABLE_NAME = 'auth_sessions' THEN
        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, payload
        ) VALUES (
            'auth_session.' || change_operation, 'auth_session',
            COALESCE(NEW.id, OLD.id)::text, 'ADMIN', '{}'::jsonb
        );
    ELSIF TG_TABLE_NAME = 'notification_deliveries' THEN
        IF COALESCE(NEW.user_id, OLD.user_id) IS NULL THEN
            IF TG_OP = 'DELETE' THEN
                RETURN OLD;
            END IF;
            RETURN NEW;
        END IF;

        INSERT INTO public.realtime_outbox (
            event_type, entity_type, entity_id, audience, target_user_id, payload
        ) VALUES (
            'notification.' || change_operation, 'notification',
            COALESCE(NEW.notification_key, OLD.notification_key)::text,
            'USER', COALESCE(NEW.user_id, OLD.user_id), '{}'::jsonb
        );
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

