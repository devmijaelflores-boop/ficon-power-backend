-- Los identificadores públicos y de entidades de negocio continúan como UUID.
-- Las tablas históricas, que crecen de manera continua, usan BIGINT secuencial
-- para reducir el tamaño de PK, índices y claves foráneas.

ALTER TABLE public.events
    ADD COLUMN compact_id bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.notification_deliveries
    ADD COLUMN compact_event_id bigint;

UPDATE public.notification_deliveries delivery
SET compact_event_id = event.compact_id
FROM public.events event
WHERE delivery.event_id = event.id;

